"""Write datasets to CSV / JSON / SQL and build a checksum manifest.

Output layout (per dataset):
    input/          what the automation is allowed to see (master data + raw documents)
    reference/      structured invoices, approvals, payments (answer key / history)
    ground_truth/   expected labels and decisions (never read by the pipeline)
    sql/            MariaDB schema + seed
    manifest.json   seed, command, row counts, SHA-256 per file
"""

import csv
import hashlib
import json
from datetime import date
from decimal import Decimal
from pathlib import Path

from apflow import __version__
from apflow.money import fmt
from apflow.schema import ALL_TABLES, TABLES, ddl


def to_str(value) -> str:
    if value is None:
        return ""
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, Decimal):
        return fmt(value)
    if isinstance(value, date):
        return value.isoformat()
    return str(value)


def serialise(rows, columns):
    return [{c: to_str(r.get(c)) for c in columns} for r in rows]


def write_csv(path: Path, rows: list, columns: list):
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", newline="", encoding="utf-8") as fh:
        w = csv.DictWriter(fh, fieldnames=columns, lineterminator="\n")
        w.writeheader()
        w.writerows(rows)


def read_csv(path: Path) -> list:
    with Path(path).open(newline="", encoding="utf-8") as fh:
        return list(csv.DictReader(fh))


def write_json(path: Path, data):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(data, indent=2, sort_keys=True, ensure_ascii=True) + "\n", encoding="utf-8", newline="\n")


def sha256(path: Path) -> str:
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def _sql_literal(value: str, ftype: str) -> str:
    if value == "":
        return "NULL"
    if ftype in ("integer", "decimal"):
        return value
    return "'" + value.replace("\\", "\\\\").replace("'", "''") + "'"


def mariadb_schema() -> str:
    schema = ["-- MariaDB schema generated by apflow (python -m apflow docs)", "SET FOREIGN_KEY_CHECKS=0;"]
    for t in ALL_TABLES:
        schema.append(f"DROP TABLE IF EXISTS {t.name};")
    for t in ALL_TABLES:
        schema.append(ddl(t, "mariadb"))
    schema.append("SET FOREIGN_KEY_CHECKS=1;")
    return "\n\n".join(schema)


def write_sql(out_dir: Path, string_tables: dict):
    sql_dir = out_dir / "sql"
    sql_dir.mkdir(parents=True, exist_ok=True)
    (sql_dir / "schema.sql").write_text(mariadb_schema() + "\n", encoding="utf-8", newline="\n")

    seed = ["-- MariaDB seed data generated by apflow. Load schema.sql first.", "SET FOREIGN_KEY_CHECKS=0;"]
    for t in ALL_TABLES:
        rows = string_tables[t.name]
        types = {f.name: f.type for f in t.fields}
        for i in range(0, len(rows), 500):
            chunk = rows[i:i + 500]
            values = ",\n".join("(" + ", ".join(_sql_literal(r[c], types[c]) for c in t.columns) + ")" for r in chunk)
            seed.append(f"INSERT INTO {t.name} ({', '.join(t.columns)}) VALUES\n{values};")
    seed.append("SET FOREIGN_KEY_CHECKS=1;")
    (sql_dir / "seed.sql").write_text("\n".join(seed) + "\n", encoding="utf-8", newline="\n")


def export_dataset(tables: dict, out_dir, policy, command: str) -> dict:
    out_dir = Path(out_dir)
    string_tables = {}
    for t in ALL_TABLES:
        rows = serialise(tables[t.name], t.columns)
        string_tables[t.name] = rows
        folder = out_dir / t.group
        write_csv(folder / f"{t.name}.csv", rows, t.columns)
        write_json(folder / "json" / f"{t.name}.json", rows)
    # ground truth also as a single JSON document keyed by invoice
    write_json(out_dir / "ground_truth" / "ground_truth.json",
               {r["invoice_id"]: r for r in string_tables["ground_truth"]})
    docs_path = out_dir / "input" / "invoice_documents.jsonl"
    with docs_path.open("w", encoding="utf-8", newline="\n") as fh:
        for d in tables["_documents"]:
            fh.write(json.dumps(d, sort_keys=True) + "\n")
    write_sql(out_dir, string_tables)

    files = sorted(p for p in out_dir.rglob("*") if p.is_file() and p.name not in ("manifest.json",)
                   and "validation" not in p.name)
    manifest = {
        "generator": "apflow", "generator_version": __version__,
        "seed": policy.seed, "scale": policy.scale, "as_of_date": policy.as_of.isoformat(),
        "policy_file": Path(policy.source_path).name, "command": command,
        "row_counts": {t.name: len(string_tables[t.name]) for t in ALL_TABLES} |
                      {"invoice_documents": len(tables["_documents"])},
        "files": {str(p.relative_to(out_dir)).replace("\\", "/"): sha256(p) for p in files},
        "provenance": {
            "external_data_used": False,
            "statement": "100% synthetic. Names, tax IDs, SKUs and amounts are generated from built-in word "
                         "lists and a fixed seed. Tax IDs use IRS-unissued EIN prefixes so they cannot match "
                         "a real business. No personal or confidential data.",
        },
    }
    write_json(out_dir / "manifest.json", manifest)
    return manifest


def load_dataset(data_dir) -> dict:
    """Load all CSV tables of a dataset as lists of string dicts."""
    data_dir = Path(data_dir)
    out = {}
    for name, t in TABLES.items():
        p = data_dir / t.group / f"{name}.csv"
        out[name] = read_csv(p) if p.exists() else []
    docs = data_dir / "input" / "invoice_documents.jsonl"
    out["_documents"] = [json.loads(line) for line in docs.read_text(encoding="utf-8").splitlines() if line] \
        if docs.exists() else []
    return out
